#!/usr/bin/env bash

# Я до сих пор сильно плаваю в bash, поэтому в этом файле будет куча комментариев как заметки
# разработчика, чтобы я мог вспомнить, что я написал вообще

# Оказывается в bash можно функции писать через $1 и $@ и так далее, то есть принимать аргументы не в скобках, а
# просто через пробел писать, что гораздо удобнее, причём их можно комбинировать. Условно пишем в одной функции
# docker compose, ещё какие-то команды, потом $@, чтобы собрать все дополнительные аргументы, а при использовании в
# качестве $@ использовать ещё функцию и так далее. В общем все функции я таким образом буду писать.

# Ещё часто в коде использую || true в тех местах, где сами тесты, чтобы ошибки наружу не проходили и не ломали тесты

# Как я понял, для всех проверяющих скриптов лучше включать строгий режим (завершает скрипт при ошибке через флаг -e
# и запрещает новые переменные создавать через флаг -u)
set -eu

# Просто переходим в нужную папку
cd "$(dirname "$0")/.."

# На всякий случай беру случайное число в конце, чтобы не совпадало с существующим контейнером
PROJECT="ipr-hw-3-check-$RANDOM"
# Здесь аналогично на всякий случай случайный порт
export HOST_PORT=$((20000 + RANDOM % 20000))
# Все переменные с путями, ссылками и прочим сразу сделал, чтобы копипаста много не было
URL="http://127.0.0.1:$HOST_PORT"
VOLUME="${PROJECT}_redis-data"
BACKUP="backups/redis-data.tar"

# Это просто шорткат, чтобы каждый раз команду не писать
dc() {
  docker compose -p "$PROJECT" "$@";
}

# Функция, которая только код запроса выводит (ошибка 503 или успех 200). -s -o /dev/null убирает весь вывод и
# Не возвращает ничего кроме кода запроса, это нужно, чтобы потом сравнивать код запроса с нужным.
code() {
  curl -s -o /dev/null -w "%{http_code}" --max-time 3 "$@" || true
}

# Мне нужна была функция, чтобы достать N для сравнения в тестах. Когда я спросил у гугла, то он предложил либо
# через jq, либо через python, а через чистый bash какая-то дикая маска, хотя вроде просто из словаря достать, но
# я её оставил.
count() {
  curl -s --max-time 3 "$URL/" | sed -n 's/.*"count": *\([0-9]*\).*/\1/p'
}

# Это нужно, чтобы закинуть как аргументы код, который мы ждём от запроса (функция чуть выше) и ссылку, по которой мы
# переходим. На всякий случай пробуем в течение 30 секунд, иначе кидаем ошибку (что-то вроде timeout, только на костылях
# наверное).
wait_for() {
  for i in $(seq 1 30); do
    [ "$(code "$URL$2")" = "$1" ] && return 0
    sleep 1
  done
  echo "Не дождались кода $1 от $2"
  exit 1
}

# Функция сравнения: что сравниваем, что хотели и что получили, если не то, что хотели, то ошибка.
check() {
  if [ "$2" != "$3" ]; then
    echo "НЕВЕРНО: $1 (ожидали $2, получили $3)"
    exit 1
  fi
  echo "ok: $1 = $3"
}

# Функция для очистки в конце скрипта.
cleanup() {
  exit_code=$?
  if [ "$exit_code" -ne 0 ]; then
    echo "Произошла ошибка во время выполнения скрипта"
    # При ошибке печатаю последние строки логов
    dc logs --tail 30 app || true
  fi
  # После завершения скрипта убираем контейнеры полностью (--remove-orphans убирает возможные оставшиеся контейнеры,
  # а --rmi all – образы).
  dc down -v --rmi all --remove-orphans || true
}
# После завершения основного скрипта чистим всё. Изначально я в самом конце trap сделал, но тут порядок важен, так как,
# как я понял, trap не выше по приоритету, чем функции, поэтому у меня до этого на какой-то ошибке падал скрипт,
# а cleanup не вызывался, так как скрипт не дошёл до trap.
trap cleanup EXIT

# Поднимаем контейнер и ждём, что сервисы работают
dc up -d --build
wait_for 200 /readyz

# Проверяем, что сначала N=0, а потом 5 раз кидаем запрос POST и проверяем, что N=5.
check "начальный count" 0 "$(count)"
for i in 1 2 3 4 5; do
  curl --max-time 3 -X POST "$URL/increment"
done
check "count после 5 POST" 5 "$(count)"

# Пересоздаём контейнер, но не трогаем redis (проверяем, что после перезапуска N сохраняется).
# Сделано через --force-recreate, чтобы не плодить контейнеры (build бы новый создал),
# --no-deps app чтобы redis не класть, а только приложение.
dc up -d --force-recreate --no-deps app
wait_for 200 /readyz
check "count после пересоздания app" 5 "$(count)"

# Теперь наоборот, кладём redis, оставляем приложение.
dc stop redis
wait_for 503 /readyz
check "/healthz без Redis" 200 "$(code "$URL/healthz")"
check "/readyz без Redis"  503 "$(code "$URL/readyz")"
check "POST без Redis"     503 "$(code -X POST "$URL/increment")"

# Теперь снова поднимаем redis и проверяем, что все работает в штатном режиме.
dc start redis
wait_for 200 /readyz
check "count после запуска Redis" 5 "$(count)"
curl --max-time 3 -X POST "$URL/increment"
check "count после ещё одного POST" 6 "$(count)"

# На этом шаге создание бэкапа. Его я вставил из того, что мне выдал гугл (переменные заменил на те, что уже сделал), но
# понимаю, как он работает. Сначала останавливаем redis и создаём папку для бэкапа. Потом по идее можно искать
# существующую папку пользователя для redis, будем поднимать отдельный контейнер, чтобы с правами доступа не было
# проблем, этот контейнер потом сразу удалится. --entrypoint tar нужен для встроенной утилиты архивации, которая как
# раз сохраняет всё, как надо по заданию (права доступа, структуру и прочее). -v "$VOLUME":/data:ro закидывает данные
# volume в папку data, которая при этом read only, чтобы ничего не сломалось. -v "$PWD/backups":/backup подключает
# локальную папку бэкапов (которую только создали) к папке бэкапов внутри нового контейнера. -C /data говорит tar, мол
# перед упаковкой иди в data (это чтобы не заархивировал лишних папок. -cpf /backup/redis-data.tar . создаёт архив с
# нужными правами и структурой и сохраняет его. [ -s "$BACKUP" ] проверяет, что всё записалось (размер бэкапа не нулевой).
dc stop app redis
mkdir -p backups
docker run --rm --entrypoint tar \
  -v "$VOLUME":/data:ro -v "$PWD/backups":/backup \
  redis:7.4-alpine -C /data -cpf /backup/redis-data.tar .
[ -s "$BACKUP" ]

echo "Проверка успешно пройдена."